import sys  # модуль для быстрого чтения ввода
 
 
def main():
    # считываем всю входную строку и разбиваем на два числа: K и N
    max_jump, total_steps = map(int, sys.stdin.read().split())
 
    # создаём массив из (total_steps + 1) нулей - по одному числу на каждую ступеньку от 0 до N
    # ways_to_reach[step] будет хранить количество способов добраться ровно до этой ступеньки
    ways_to_reach = [0] * (total_steps + 1)
 
    # до ступеньки 0 (земля, старт) есть ровно 1 способ - никуда не прыгать
    ways_to_reach[0] = 1
 
    # перебираем все ступеньки по очереди, начиная с 1-й и заканчивая последней (N-й)
    for step in range(1, total_steps + 1):
 
        # здесь будем накапливать сумму способов добраться до текущей ступеньки
        ways_for_this_step = 0
 
        # перебираем все возможные длины последнего прыжка: от 1 до max_jump
        for jump_length in range(1, max_jump + 1):
 
            # вычисляем, с какой ступеньки был бы сделан такой прыжок
            previous_step = step - jump_length
 
            # если такая ступенька существует (не ушли ниже нуля)
            if previous_step >= 0:
                # прибавляем к сумме количество способов добраться до предыдущей ступеньки
                ways_for_this_step += ways_to_reach[previous_step]

 
 
        # сохраняем посчитанную сумму как результат для текущей ступеньки
        ways_to_reach[step] = ways_for_this_step
 
    # выводим итоговый ответ - количество способов добраться до самой верхней ступеньки
    print(ways_to_reach[total_steps])
 
 
# эта проверка нужна, чтобы main() запускался только при прямом запуске файла
if __name__ == "__main__": 
    main()
    